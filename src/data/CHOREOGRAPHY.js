// cards, modals and watch-progress plumbing all work unchanged, and adds the
// fields the choreography views filter on:
//
//   type    "choreography" | "practice" | "dance-version" | "performance" | "fancam"
//   song    the track the clip performs (drives the "Song A–Z" sort)
//   members member ids (see utils/memberMatch.js); an empty array means the
//           full group. `sub` stays the display label used by the member chips.
//   era     an id from data/ERAS.js, so a clip can be grouped by chapter (only
//           set where the chapter is certain; otherwise "" and it is skipped by
//           the era filter)
//
