// channel uploads the sync script writes to src/data/youtubeVideos.json, so the
// Choreography page shows hand-picked clips plus anything the channel posted
// recently that matches the choreography keywords. Items that lack a real
// video id are skipped there rather than rendered as broken cards, so a
// half-finished entry can never blank out the page.

